import { Check, Clapperboard, FolderOpen, Image, Loader2, Play, RefreshCw, Settings2, Sparkles, TerminalSquare } from "lucide-react";
import { isTauri } from "@tauri-apps/api/core";
import { useI18n } from "../i18n";
import { media } from "../api";
import type { Segment } from "../types";

type Kind = "image" | "hf";
type StepState = "done" | "todo" | "active" | "waiting";

/** One numbered step of a segment's visual, with its state and actions. */
function Step({ number, state, title, status, children }: { number: number; state: StepState; title: string; status: React.ReactNode; children?: React.ReactNode }) {
  return (
    <li className={`visual-step ${state}`}>
      <span className="visual-step-dot" aria-hidden="true">
        {state === "done" ? <Check size={12} strokeWidth={3} /> : state === "active" ? <Loader2 size={12} className="spin" /> : number}
      </span>
      <div className="visual-step-body">
        <div className="visual-step-heading">
          <strong>{title}</strong>
          <span className="visual-step-status">{status}</span>
        </div>
        {children}
      </div>
    </li>
  );
}

/**
 * How one segment gets its picture: a still image, or motion that Claude Code designs and
 * Studio renders. Every output it mentions is one click away (preview, keyframes, folder).
 */
export default function SegmentVisual({
  project,
  segment,
  opening,
  version,
  stale,
  locked,
  narrationDirty,
  agentSegments,
  agentHere,
  rendering,
  generating,
  previewing,
  onKind,
  onGenerateStill,
  onDesign,
  onFinish,
  onRender,
  onPreview,
  onGoTo,
  onSettings,
  onShowFiles,
}: {
  project: string;
  segment: Segment | undefined;
  /** The opening has a generated still and no motion option. */
  opening: { visual: string | null } | null;
  version: number;
  /** Why this segment's visual is out of date, if it is. */
  stale: string | null;
  /** A job, agent, or request is running somewhere in the project. */
  locked: boolean;
  narrationDirty: boolean;
  /** Segments an open Claude Code session is working on (empty when none). */
  agentSegments: number[];
  agentHere: boolean;
  rendering: boolean;
  generating: boolean;
  previewing: string | null;
  onKind: (kind: Kind) => void;
  onGenerateStill: () => void;
  onDesign: () => void;
  onFinish: () => void;
  onRender: () => void;
  onPreview: (path: string | null) => void;
  onGoTo: (index: number) => void;
  onSettings: () => void;
  onShowFiles: (folder: string) => void;
}) {
  const { t, locale } = useI18n();
  const kind: Kind = opening ? "image" : segment?.visualizer === "hf" ? "hf" : "image";
  const motion = segment?.motion;
  const elsewhere = agentSegments.length > 0 && !agentHere ? agentSegments[0] : null;
  const time = (seconds: number) =>
    new Date(seconds * 1000).toLocaleTimeString(locale, { hour: "numeric", minute: "2-digit" });

  const still = opening ? opening.visual : segment?.visualizer === "image" ? segment.visual : null;
  const stillReady = Boolean(still && /\.(png|jpe?g)$/i.test(still));

  const composed = motion?.composed ? t("Saved {time}", { time: time(motion.composed) }) : "";
  const designState: StepState = agentHere ? "active" : motion?.composition ? "done" : "todo";
  const keyframes = motion?.keyframes || [];
  const renderState: StepState = rendering ? "active" : motion?.video_current && motion.video ? "done" : motion?.composition ? "todo" : "waiting";

  return (
    <section className="segment-visual" aria-label={t("Segment visual")}>
      <div className="segment-visual-heading">
        <span>{opening ? t("Opening visual") : t("Segment visual")}</span>
        <button className="icon-button" title={t("Visual settings")} aria-label={t("Visual settings")} onClick={onSettings}>
          <Settings2 size={15} />
        </button>
      </div>

      {!opening && (
        <div className="visual-kind" role="radiogroup" aria-label={t("Segment visual type")}>
          {([
            ["image", Image, t("Still image"), t("Generated by the image service")],
            ["hf", Clapperboard, t("Motion"), t("Designed by Claude Code, rendered by Studio")],
          ] as const).map(([value, Icon, label, hint]) => (
            <button key={value} role="radio" aria-checked={kind === value} title={narrationDirty ? t("Save your narration edit first.") : hint}
              disabled={kind !== value && (locked || narrationDirty)}
              onClick={() => kind !== value && onKind(value)}>
              <Icon size={15} />
              <span>
                <strong>{label}</strong>
                <small>{hint}</small>
              </span>
            </button>
          ))}
        </div>
      )}

      {kind === "image" ? (
        <ol className="visual-steps">
          <Step number={1} state={generating ? "active" : stillReady && !stale ? "done" : "todo"} title={t("Image")}
            status={generating ? t("Generating…") : stale && stillReady ? t("Out of date") : stillReady ? t("Ready") : t("Not generated")}>
            {stale && <p className="visual-step-note">{t(stale)}</p>}
            <div className="visual-step-actions">
              <button className={`button small${stillReady && !stale ? "" : " primary"}`} disabled={locked} onClick={onGenerateStill}>
                {stillReady ? <RefreshCw size={13} /> : <Sparkles size={13} />}
                {stillReady ? t("Regenerate image") : t("Generate image")}
              </button>
            </div>
          </Step>
        </ol>
      ) : (
        <ol className="visual-steps">
          <Step number={1} state={designState} title={t("Design with Claude Code")}
            status={agentHere ? t("Session open") : composed || t("Not designed yet")}>
            {agentHere ? (
              <>
                <p className="visual-step-note">
                  {motion?.composition
                    ? t("Composition saved {time}. When Claude Code says it is ready, finish the session to render it.", { time: motion.composed ? time(motion.composed) : "" })
                    : t("Claude Code is designing this segment in the right pane. Its composition appears here when saved.")}
                </p>
                <div className="visual-step-actions">
                  <button className="button small primary" disabled={!motion?.composition} onClick={onFinish}>
                    <Play size={13} /> {t("Finish & render")}
                  </button>
                </div>
              </>
            ) : elsewhere !== null ? (
              <>
                <p className="visual-step-note">{t("Claude Code is working on segment {index}.", { index: elsewhere })}</p>
                <div className="visual-step-actions">
                  <button className="button small" onClick={() => onGoTo(elsewhere)}>{t("Go to segment {index}", { index: elsewhere })}</button>
                </div>
              </>
            ) : (
              <div className="visual-step-actions">
                <button className={`button small${motion?.composition ? "" : " primary"}`} disabled={locked || narrationDirty} onClick={onDesign}>
                  <TerminalSquare size={13} /> {motion?.composition ? t("Revise with Claude Code") : t("Design with Claude Code")}
                </button>
              </div>
            )}
          </Step>

          <Step number={2} state={keyframes.length ? (motion?.keyframes_current ? "done" : "todo") : "waiting"} title={t("Keyframes")}
            status={keyframes.length ? (motion?.keyframes_current ? t("{count} frames", { count: keyframes.length }) : t("From an earlier version")) : t("None yet")}>
            {keyframes.length > 0 ? (
              <div className="keyframe-strip">
                {keyframes.map((frame, i) => (
                  <button key={frame} className={previewing === frame ? "selected" : ""} aria-pressed={previewing === frame}
                    title={t("Show keyframe {index} in the preview", { index: i + 1 })}
                    onClick={() => onPreview(previewing === frame ? null : frame)}>
                    <img loading="lazy" src={media(project, frame, version)} alt={t("Keyframe {index}", { index: i + 1 })} />
                  </button>
                ))}
              </div>
            ) : (
              <p className="visual-step-note">{t("Claude Code's snapshot check saves keyframes here, so you can review the design before rendering.")}</p>
            )}
          </Step>

          <Step number={3} state={renderState} title={t("Video")}
            status={rendering ? t("Rendering…") : !motion?.video ? t("Not rendered") : motion.video_current ? t("Up to date") : t("Out of date")}>
            {!rendering && motion?.video && !motion.video_current && (
              <p className="visual-step-note">{t("The composition changed after this video was rendered.")}</p>
            )}
            {!rendering && motion?.composition && !(motion.video && motion.video_current) && (
              <div className="visual-step-actions">
                <button className="button small primary" disabled={locked} onClick={onRender}>
                  <Play size={13} /> {t("Render video")}
                </button>
              </div>
            )}
            {!motion?.composition && <p className="visual-step-note">{t("Renders automatically when the Claude Code session ends.")}</p>}
          </Step>
        </ol>
      )}

      {kind === "hf" && motion && (
        <div className="segment-visual-footer">
          <button className="text-link" disabled={!isTauri() || !motion.composition} onClick={() => onShowFiles(motion.folder)}
            title={motion.folder}>
            <FolderOpen size={13} /> {t("Show files")}
          </button>
          {segment?.still && <span className="small-muted">{t("Still image kept for switching back")}</span>}
        </div>
      )}
    </section>
  );
}
