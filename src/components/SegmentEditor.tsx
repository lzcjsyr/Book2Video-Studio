import { Clapperboard, Image, Search } from "lucide-react";
import { useEffect, useRef } from "react";
import { useI18n } from "../i18n";
import type { Segment } from "../types";

// Grow each narration box to fit its text so the list reads like a document.
const fit = (el: HTMLTextAreaElement | null) => {
  if (!el) return;
  el.style.height = "auto";
  el.style.height = el.scrollHeight + "px";
};

export default function SegmentEditor({
  segments,
  draft,
  selected,
  search,
  locked,
  onSearch,
  onSelect,
  onEdit,
}: {
  segments: Segment[];
  draft: Segment[];
  selected: number;
  search: string;
  locked: boolean;
  onSearch: (value: string) => void;
  onSelect: (index: number) => void;
  onEdit: (index: number, key: "content" | "visualizer", value: string) => void;
}) {
  const { t } = useI18n();
  // Keep the selected row on screen when it is chosen elsewhere, such as in the sequence.
  const active = useRef<HTMLDivElement | null>(null);
  useEffect(() => {
    active.current?.scrollIntoView({ block: "nearest", behavior: "smooth" });
  }, [selected]);
  const saved = new Map(segments.map((s) => [s.index, s]));
  const rows = draft.filter(
    (s) =>
      !search || s.content.includes(search) || String(s.index).includes(search),
  );
  return (
    <div className="segment-editor-list">
      <div className="search-field">
        <Search size={14} />
        <input
          aria-label={t("Search segments")}
          value={search}
          onChange={(e) => onSearch(e.target.value)}
          placeholder={t("Find a segment or phrase…")}
        />
      </div>
      {rows.map((s) => {
        const motion = s.visualizer === "hf";
        const before = saved.get(s.index);
        return (
          <div
            key={s.index}
            ref={s.index === selected ? active : undefined}
            className={`segment-row ${s.index === selected ? "active" : ""}`}
            onClick={() => onSelect(s.index)}
          >
            <span className="mono">{String(s.index).padStart(3, "0")}</span>
            <textarea
              ref={fit}
              rows={1}
              aria-label={t("Narration for segment {index}", { index: s.index })}
              value={s.content}
              onFocus={() => onSelect(s.index)}
              onChange={(e) => {
                fit(e.currentTarget);
                onEdit(s.index, "content", e.target.value);
              }}
            />
            <div
              className="visual-toggle"
              role="group"
              aria-label={t("Segment visual type")}
            >
              <button
                aria-pressed={!motion}
                disabled={locked}
                title={t("Generated by the image API in Step 4")}
                onClick={() => onEdit(s.index, "visualizer", "image")}
              >
                <Image size={12} /> {t("Image")}
              </button>
              <button
                aria-pressed={motion}
                disabled={locked}
                title={t("Created by Claude Code with HTML / Three.js in Step 4")}
                onClick={() => onEdit(s.index, "visualizer", "hf")}
              >
                <Clapperboard size={12} /> {t("Motion")}
              </button>
            </div>
            <span className="mono muted">
              {(before?.duration ?? before?.estimated_duration ?? 0).toFixed(1)}
              {t("s")}
            </span>
          </div>
        );
      })}
    </div>
  );
}
